import { useCallback, useEffect, useMemo, useState, type FormEvent } from 'react';
import { Link } from 'react-router-dom';
import { api } from '../api';
import { useApi, useMessage } from '../hooks';
import { Alert } from '../Layout';
import { DataState, Empty, IconLabel, Modal } from '../ui';

export interface Teacher {
  teacher_id: number; first_name: string; last_name: string; email: string;
  department: string | null; is_active: boolean | number; assigned_sections: number; has_account?: number;
}

interface ClassData {
  classes: { class_id: number; class_name: string; subject: string | null; teacher_id: number | null }[];
  sections: { section_id: number; section_name: string; class_id: number | null; class_name: string | null }[];
}

interface RosterStudent {
  student_id: number; student_no: string; first_name: string; middle_name: string | null;
  last_name: string; section_name: string; class_name: string;
}

type TeacherFields = Pick<Teacher, 'first_name' | 'last_name' | 'email' | 'department' | 'is_active'>;
const EMPTY: TeacherFields = { first_name: '', last_name: '', email: '', department: '', is_active: true };
const active = (teacher: Teacher) => teacher.is_active === true || teacher.is_active === 1;

export function TeacherForm({ teacherId, initial = EMPTY, submitLabel, onSubmit }: {
  teacherId?: number; initial?: TeacherFields; submitLabel: string; onSubmit: (teacher: TeacherFields) => Promise<boolean>;
}) {
  const [form, setForm] = useState<TeacherFields>({ ...initial });
  const setText = (key: 'first_name' | 'last_name' | 'email' | 'department') => (e: { target: { value: string } }) =>
    setForm({ ...form, [key]: e.target.value });
  const submit = async (e: FormEvent) => { e.preventDefault(); await onSubmit(form); };
  return (
    <form onSubmit={submit}>
      <div className="form-row">
        <div className="form-group"><label>Teacher ID</label><input readOnly value={teacherId ?? 'Assigned automatically'} /></div>
        <div className="form-group"><label>First name</label><input required maxLength={80} value={form.first_name} onChange={setText('first_name')} /></div>
        <div className="form-group"><label>Last name</label><input required maxLength={80} value={form.last_name} onChange={setText('last_name')} /></div>
        <div className="form-group"><label>Email</label><input type="email" required maxLength={150} value={form.email} onChange={setText('email')} /></div>
        <div className="form-group"><label>Program / department</label><input maxLength={100} value={form.department ?? ''} onChange={setText('department')} /></div>
        <div className="form-group"><label>Status</label>
          <select value={form.is_active ? 'active' : 'inactive'} onChange={e => setForm({ ...form, is_active: e.target.value === 'active' })}>
            <option value="active">Active</option><option value="inactive">Inactive</option>
          </select>
        </div>
      </div>
      <p className="muted">Teacher IDs are generated by the database. The current record does not store middle names or contact numbers.</p>
      <button type="submit" className="btn btn-primary"><IconLabel icon="save">{submitLabel}</IconLabel></button>
    </form>
  );
}

export default function Teachers() {
  const { data: teachers, loading, error, reload } = useApi<Teacher[]>('/teachers');
  const { data: classes, reload: reloadClasses } = useApi<ClassData>('/classes');
  const { msg, run } = useMessage();
  const [search, setSearch] = useState('');
  const [department, setDepartment] = useState('');
  const [status, setStatus] = useState('');
  const [adding, setAdding] = useState(false);
  const [editing, setEditing] = useState<Teacher | null>(null);
  const [assigning, setAssigning] = useState<Teacher | null>(null);
  const [classIds, setClassIds] = useState<number[]>([]);
  const [rosterTeacher, setRosterTeacher] = useState<Teacher | null>(null);
  const [rosterSearch, setRosterSearch] = useState('');
  const closeForm = useCallback(() => { setAdding(false); setEditing(null); }, []);
  const closeAssignment = useCallback(() => setAssigning(null), []);
  const closeRoster = useCallback(() => setRosterTeacher(null), []);
  const { data: roster, loading: rosterLoading, error: rosterError, reload: reloadRoster } =
    useApi<RosterStudent[]>(rosterTeacher ? `/teachers/${rosterTeacher.teacher_id}/students` : null);

  useEffect(() => {
    if (assigning && classes) {
      setClassIds(classes.classes.filter(c => c.teacher_id === assigning.teacher_id).map(c => c.class_id));
    }
  }, [assigning, classes]);

  const departments = useMemo(() => [...new Set((teachers ?? []).map(t => t.department?.trim()).filter((v): v is string => !!v))].sort(), [teachers]);
  const shown = useMemo(() => {
    const needle = search.trim().toLowerCase();
    return (teachers ?? []).filter(t =>
      (!needle || `${t.teacher_id} ${t.first_name} ${t.last_name} ${t.email}`.toLowerCase().includes(needle)) &&
      (!department || t.department === department) &&
      (!status || (active(t) ? status === 'active' : status === 'inactive')));
  }, [teachers, search, department, status]);
  const total = teachers?.length ?? 0;
  const activeCount = teachers?.filter(active).length ?? 0;
  const assignedCount = teachers?.filter(t => Number(t.assigned_sections) > 0).length ?? 0;
  const shownRoster = (roster ?? []).filter(student =>
    `${student.student_no} ${student.first_name} ${student.middle_name ?? ''} ${student.last_name} ${student.section_name}`
      .toLowerCase().includes(rosterSearch.trim().toLowerCase()));

  const addTeacher = async (fields: TeacherFields) => {
    const ok = await run(() => api('/teachers', { body: fields }), 'Teacher added.');
    if (ok) { closeForm(); reload(); }
    return ok;
  };
  const saveTeacher = async (fields: TeacherFields) => {
    if (!editing) return false;
    const ok = await run(() => api(`/teachers/${editing.teacher_id}`, { method: 'PUT', body: fields }), 'Teacher updated.');
    if (ok) { closeForm(); reload(); reloadClasses(); }
    return ok;
  };
  const toggleStatus = (teacher: Teacher) => {
    const next = !active(teacher);
    if (!next && !confirm(`Deactivate ${teacher.first_name} ${teacher.last_name}? Their records and class history will be preserved.`)) return;
    run(async () => {
      await api(`/teachers/${teacher.teacher_id}`, { method: 'PUT', body: {
        first_name: teacher.first_name, last_name: teacher.last_name, email: teacher.email,
        department: teacher.department ?? '', is_active: next,
      } });
      reload();
    }, next ? 'Teacher activated.' : 'Teacher deactivated.');
  };
  const openAssignments = (teacher: Teacher) => {
    setClassIds(classes?.classes.filter(c => c.teacher_id === teacher.teacher_id).map(c => c.class_id) ?? []);
    setAssigning(teacher);
  };
  const saveAssignments = () => {
    if (!assigning) return;
    const replacing = (classes?.classes ?? []).some(c => classIds.includes(c.class_id) && c.teacher_id != null && c.teacher_id !== assigning.teacher_id);
    if (replacing && !confirm('Some selected classes belong to another teacher. Reassign them and include all sections in those classes?')) return;
    run(async () => {
      const result = await api<{ reassigned: number }>(`/teachers/${assigning.teacher_id}/assignments`, {
        method: 'PUT', body: { class_ids: classIds },
      });
      closeAssignment(); reload(); reloadClasses();
      return result;
    }, 'Teacher class assignments saved.');
  };

  return (
    <>
      <Alert msg={msg} />
      <div className="teacher-summary stats-grid">
        <Summary label="Total teachers" count={total} />
        <Summary label="Active" count={activeCount} />
        <Summary label="With assigned sections" count={assignedCount} />
        <Summary label="Unassigned" count={Math.max(0, total - assignedCount)} />
      </div>
      <div className="toolbar">
        <button className="btn btn-primary add-btn" onClick={() => setAdding(true)}><IconLabel icon="plus">Add teacher</IconLabel></button>
        <label className="search"><input aria-label="Search teachers" placeholder="Search ID, name or email" value={search} onChange={e => setSearch(e.target.value)} /></label>
        <select aria-label="Filter by department" value={department} onChange={e => setDepartment(e.target.value)}>
          <option value="">All departments</option>{departments.map(d => <option key={d}>{d}</option>)}
        </select>
        <select aria-label="Filter by status" value={status} onChange={e => setStatus(e.target.value)}>
          <option value="">All statuses</option><option value="active">Active</option><option value="inactive">Inactive</option>
        </select>
      </div>
      {teachers === null || error
        ? <DataState loading={loading} error={error} onRetry={reload} />
        : teachers.length === 0
          ? <Empty><p>No teachers yet. Press <strong>Add teacher</strong> to add one.</p></Empty>
          : <div className="card teacher-table-card">
              <table>
                <thead><tr><th>Teacher ID</th><th>Full name</th><th>Email</th><th>Program / department</th><th>Assigned sections</th><th>Status</th><th>Actions</th></tr></thead>
                <tbody>{shown.length ? shown.map(teacher => (
                  <tr key={teacher.teacher_id}>
                    <td>{teacher.teacher_id}</td>
                    <td><strong>{teacher.last_name}, {teacher.first_name}</strong></td>
                    <td>{teacher.email}</td>
                    <td>{teacher.department || <span className="muted">—</span>}</td>
                    <td>{Number(teacher.assigned_sections) || 0}</td>
                    <td><span className={`badge ${active(teacher) ? 'badge-present' : 'badge-muted'}`}>{active(teacher) ? 'Active' : 'Inactive'}</span></td>
                    <td><div className="row-actions teacher-actions">
                      <button className="btn btn-outline btn-sm" onClick={() => setEditing(teacher)}>Edit</button>
                      <button className="btn btn-outline btn-sm" disabled={!classes} onClick={() => openAssignments(teacher)}>Assign sections</button>
                      <button className="btn btn-outline btn-sm" onClick={() => setRosterTeacher(teacher)}>View students</button>
                      <Link className="btn btn-outline btn-sm" to={`/teachers/${teacher.teacher_id}/edit`}>Sign-in</Link>
                      <button className="btn btn-outline btn-sm" onClick={() => toggleStatus(teacher)}>{active(teacher) ? 'Deactivate' : 'Activate'}</button>
                    </div></td>
                  </tr>
                )) : <tr><td colSpan={7} className="teacher-no-results">No teachers match these filters.</td></tr>}</tbody>
              </table>
            </div>}

      {adding && <Modal title="Add teacher" onClose={closeForm}>
        <TeacherForm submitLabel="Save teacher" onSubmit={addTeacher} />
      </Modal>}
      {editing && <Modal title="Edit teacher" subtitle={`Teacher ID ${editing.teacher_id}`} onClose={closeForm}>
        <TeacherForm key={editing.teacher_id} teacherId={editing.teacher_id} initial={{
          first_name: editing.first_name, last_name: editing.last_name, email: editing.email,
          department: editing.department ?? '', is_active: active(editing),
        }} submitLabel="Save changes" onSubmit={saveTeacher} />
      </Modal>}
      {assigning && classes && <Modal title="Assign classes and sections" subtitle={`${assigning.first_name} ${assigning.last_name} · Teacher ID ${assigning.teacher_id}`} onClose={closeAssignment}>
        <p className="muted">Assignments use the existing class-to-teacher relationship: choosing a class includes every section under it. A selected class will be reassigned from its current teacher.</p>
        <div className="teacher-class-options">
          {classes.classes.map(cls => {
            const checked = classIds.includes(cls.class_id);
            const owned = cls.teacher_id === assigning.teacher_id;
            const sections = classes.sections.filter(section => section.class_id === cls.class_id);
            return <label className="teacher-class-option" key={cls.class_id}>
              <input type="checkbox" checked={checked} disabled={!active(assigning) && !owned} onChange={e => setClassIds(ids =>
                e.target.checked ? [...ids, cls.class_id] : ids.filter(id => id !== cls.class_id))} />
              <span><strong>{cls.class_name}</strong><span className="muted">{sections.map(section => section.section_name).join(', ') || 'No sections'}{cls.teacher_id && !owned ? ' · assigned to another teacher' : ''}</span></span>
            </label>;
          })}
          {classes.classes.length === 0 && <Empty><p>Create a class and its sections in School Setup first.</p></Empty>}
          {classes.sections.some(section => !section.class_id) && <p className="muted">Sections without a class cannot be assigned using the current school data structure. Link them to a class in School Setup first.</p>}
        </div>
        <button className="btn btn-primary" disabled={classes.classes.length === 0} onClick={saveAssignments}><IconLabel icon="save">Save assignments</IconLabel></button>
      </Modal>}
      {rosterTeacher && <Modal title="Assigned students" subtitle={`${rosterTeacher.first_name} ${rosterTeacher.last_name} · Teacher ID ${rosterTeacher.teacher_id}`} onClose={closeRoster}>
        <DataState loading={rosterLoading} error={rosterError} onRetry={reloadRoster} />
        {roster && (roster.length === 0 ? <Empty><p>No students belong to this teacher’s assigned sections.</p></Empty> :
          <div className="teacher-roster-table">
            <label className="search"><input aria-label="Search assigned students" placeholder="Search ID, name or section" value={rosterSearch} onChange={e => setRosterSearch(e.target.value)} /></label>
            <table><thead><tr><th>Student ID</th><th>Student name</th><th>Section</th></tr></thead>
            <tbody>{shownRoster.length ? shownRoster.map(student => <tr key={student.student_id}><td>{student.student_no}</td><td>{student.last_name}, {student.first_name}{student.middle_name ? ` ${student.middle_name}` : ''}</td><td>{student.section_name}</td></tr>)
              : <tr><td colSpan={3} className="teacher-no-results">No students match this search.</td></tr>}</tbody>
          </table></div>)}
      </Modal>}
    </>
  );
}

function Summary({ label, count }: { label: string; count: number }) {
  return <div className="stat-card"><div className="stat-num">{count}</div><div className="stat-label">{label}</div></div>;
}
